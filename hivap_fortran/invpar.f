      SUBROUTINE INVPAR(EQ,F,RZERO,D,AP,ZP,AT,ZT,SIGML,FLGRAZ)
C
C  Vereinfachte Version von PARAP, wird zusammen mit FUSION benutzt
C  Stand: 3.5.1994
C
      IMPLICIT REAL*8 (A-H,O-Z)
      DIMENSION SIGML(1)
C
C     CALCULATION OF NUCLEAR CROSS SECTIONS
C     WITH PARABOLIC BARRIER - SEE THOMAS, PHYS REV 116,703 (1959) -
      EN=EQ
      DO1 I=1,200
 1    SIGML(I)=0.
      LMAX=200
 2    WRITE(6,1001)
 1001 FORMAT(1H0,'INVERTED PARABOLA'/)
      LMAX=LMAX+1
      COUL=(1.4393)*ZT*ZP
      AR=AT**0.333333+AP**0.333333
      RA=RZERO*AR
C
      PRINT 1007,F,D,RZERO,RA
 1007 FORMAT(1H0,'F,D,RZERO,RA',4F10.3/)
      PRINT 1003
 1003 FORMAT(5X,'L',6X,'TL',13X,'RB',10X,'VB', 10X,'WL',10X,'SIGL')
      U=AT*AP/(AT+AP)
      H2=41.814
      ACN=AP+AT
      CR2=D*COUL/F
      CR3P=H2*D/(F*U)
 6    E=EN*AT/(AT+AP)
      EL=EN
      PWAVE=SQRT(2.*931.16*U*E)
      WAVEL=19.732/PWAVE
      ARWAVE=3141.59*(WAVEL**2)
      TOTSIG=0.
      TL2=0.
      IREP=0
      RB=0.
C
      DO 29 K=1,LMAX
      L=K-1
      R=RB
      IF(L.EQ.0)R=RA
      RB=0.
      AL=FLOAT(L)
      CR3=CR3P*AL*(AL+1)
 9    DUM=CR2/R**2+CR3/R**3
      IF(DUM)91,91,90
 91   IF(RB)900,900,11
 90   RB=RA-D*DLOG(DUM)
      DELTR=ABS(RB-R)
      IF(DELTR-0.01)11,10,10
 10   R=RB
      GO TO 9
 11   CONTINUE
      R0=RB/AR
      VLB=COUL/RB+(H2/2./U)*(AL*(AL+1)/RB**2)-F*EXP(-(RB-RA)/D)
      D2VLB=2.*COUL/RB**3+(H2/U)*3.*AL*(AL+1)/RB**4
     1 -(F/D**2)*EXP(-(RB-RA)/D)
      IF(D2VLB) 12,13,14
 12   SD2VLB=-1.0
      GO TO 15
 13   SD2VLB=0.0
      GO TO 15
 14   SD2VLB=1.0
 15   CONTINUE
      WL2=ABS((H2/U)*D2VLB)
      WL=SQRT(WL2)
      DUM=2.*3.14159*(VLB-E)/WL
      IF(DUM.LT.-20.) GOTO 152
      TL=1./(1.+EXP(DUM))
      GOTO 155
 152  TL=1.
 155  CONTINUE
      RSIGL=TL*(2.*AL+1.)
      SIGL=ARWAVE*RSIGL
      SIGML(K)=SIGL
      TOTSIG=TOTSIG+SIGL
      IF(TL.LT.0.5) IREP=IREP+1
      IF(IREP.GE.2) GOTO 20
      FLGRAZ=L-1
      TL1=TL2
      TL2=TL
      IF(L.EQ.0) TL0=TL
 20   CONTINUE
      IF( (TL.LT.0.99).OR.(L.EQ.1) )
     1PRINT 1011,L,TL,RB,VLB,WL,SIGL
 1011 FORMAT(I6,F12.6,4F12.3)
      IF(TL-.0001)30,29,29
 29   CONTINUE
 30   CONTINUE
      LMAX=K-1
      IF(TL0.LT.0.5) GOTO 32
      FLGRAZ=FLGRAZ+(TL1-0.5)/(TL1-TL2)
 32   IF(FLGRAZ.LT.0.)FLGRAZ=0.
      FLGR2=FLGRAZ*FLGRAZ
      WRITE(6,1012) FLGRAZ,LMAX,TOTSIG,FLGR2,E
 1012 FORMAT(//1H0,'LGRAZE,LMAX,TOTSIG,LGRAZE2,ECM',F8.1,I8,4X,
     1 F8.3,F8.0,F10.1//)
C
 900  PRINT 1020
 1020 FORMAT(1H0,'NEG.ARG. FOR LOG'/)
      RETURN
      END