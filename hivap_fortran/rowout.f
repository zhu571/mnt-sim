      SUBROUTINE  ROWOUT(NROW,LOGUN,SIGMXZ,NOPUT,EXCIT0)
C
C  Steuert Datenausgabe
C  Stand: 3.5.1994
C
      INCLUDE 'common.f'
                     LOGUN=6
      IF(LPRINT.GT.3)LOGUN=22
      SIGZ(NROW)=0.
      DO 30 NSTEP=1,NA
      XSECT(NROW,NSTEP)=SIG(NSTEP)
      SIGFIS=SIGFIS+RLOSTF(NSTEP)
      SIGEVA=SIGEVA+SIG(NSTEP)
 30   SIGZ(NROW)=SIGZ(NROW)+SIG(NSTEP)
      SIGMXZ=DMAX1(SIGMXZ,SIGZ(NROW))
C
      IF(LPRINT.GE.3) THEN
         DO 31 K=1,KEG
         SPECGT(K)=SPECGT(K)+SPECG(K)
 31      SPECQT(K)=SPECQT(K)+SPECQ(K)
         DO 32 K=1,KEN
 32      SPECNT(K)=SPECNT(K)+ SPECN(K)
         DO 33 K=1,KEP1
 33      SPECPT(K)=SPECPT(K)+SPECP(K)
         DO 34 K=1,KEA1
 34      SPECAT(K)=SPECAT(K)+SPECA(K)
         DO 35 K=1,KEF
 35      SPECFT(K)=SPECFT(K)+SPECF(K)
      ENDIF
C
      MZ=KZ(NROW)
      IF(LPRINT.GT.3)GOTO 116
      WRITE(LOGUN,50) NROW,ELEMNT(MZ),SIGZ(NROW)
 50   FORMAT(1H1,4X,'ROW',I3,6X,'ELEMENT ',A4,4X,'X-SECTION',E12.3)
 55   WRITE (LOGUN,101)(TITLE(I),I=1,18)
 101  FORMAT   ( 18A4)
      WRITE(LOGUN,110) ELAB,QC,EXCIT0
 110  FORMAT(' ELAB(MEV)',F9.3,5X,'Q-VALUE' ,F9.3,4X,'EXCIT',F9.3)
      WRITE (LOGUN,114) SIGFUS,SIGEVA,SIGFIS,SIGMXZ
 114  FORMAT(' SIGFUS,SIGEVA,SIGFIS,SIGMXZ',4E12.4)
C     FOR PLT02

C	BY KZHAO/2006/12/12 FOR OUTPUT CROSS-SECTION
      DO NSTEP=1,NA
	WRITE(1236,'(3E20.12,2I8,2E20.12)')
     +ELAB,ELAB*MTGT/(MTGT+MPROJ),
     +SIGFUS,NROW,NSTEP,SIG(NSTEP),RLOSTF(NSTEP)
	ENDDO

 116                  GOTO 160
 120  FORMAT( 9F8.3)
 130  FORMAT(18I4)
C
 160  IF(LPRINT.GT.3) GOTO 340
      WRITE(LOGUN,170)IZT,MTGT,IZP,MPROJ
 170  FORMAT(' ZT=',I3,4X,'AT',I4,4X,'ZP',I3,4X,'AP',I4//)
C---------------------------------------------------------------
      NA1=1
      NA2=MIN0(12,NA)
 171  DO 175 NSTEP=1,NA
 175  IND(NSTEP)=MZ+IN(NSTEP)
      WRITE(LOGUN,176) (IND(NSTEP),ELEMNT(MZ),NSTEP=NA1,NA2)
 176  FORMAT(11X,12(2X,I3,A4,1X))
      WRITE(LOGUN,180)(SIG(NSTEP) ,NSTEP=NA1 ,NA2)
 180  FORMAT(' SIG',7X,12E10.3)
      DO 182 NSTEP=NA1,NA2
      IND(NSTEP)=0
      IF(TOTAL(NSTEP).GT.0.)IND(NSTEP)=SIG  (NSTEP)*10000./TOTAL(NSTEP)
     1                                 +.5
 182  CONTINUE
      WRITE(LOGUN,183)(IND(NSTEP) ,NSTEP=NA1 ,NA2)
 183  FORMAT(' B-G',6X,12I10  )
      DO 185 NSTEP=NA1,NA2
      IND(NSTEP)=0
      IF(TOTAL(NSTEP).GT.0.)IND(NSTEP)=SIGNN(NSTEP)*10000./TOTAL(NSTEP)
     1                                 +.5
 185  CONTINUE
      WRITE(LOGUN, 190)(IND  (NSTEP),NSTEP=NA1 ,NA2)
 190  FORMAT('  R-N',5X,12I10)
      DO 195 NSTEP=NA1,NA2
      IND(NSTEP)=0
      IF(TOTAL(NSTEP).GT.0.)IND(NSTEP)=SIGP (NSTEP)*10000./TOTAL(NSTEP)
     1                                 +.5
 195  CONTINUE
      WRITE(LOGUN,200)( IND (NSTEP),NSTEP=NA1,NA2)
 200  FORMAT(' BR-P',5X,12I10  )
      DO 205 NSTEP=NA1,NA2
      IND(NSTEP)=0
      IF(TOTAL(NSTEP).GT.0.)IND(NSTEP)=SIGA (NSTEP)*10000./TOTAL(NSTEP)
     1                                 +.5
 205  CONTINUE
      WRITE(LOGUN,210)( IND (NSTEP),NSTEP=NA1,NA2)
 210  FORMAT(' BR-A'  ,5X,12I10  )
      DO 209 NSTEP=NA1,NA2
      IND(NSTEP)=0
      IF(TOTAL(NSTEP).GT.0.)IND(NSTEP)=SIGF (NSTEP)*10000./TOTAL(NSTEP)
     1                                 +.5
 209  CONTINUE
      IF(NOF.EQ.0) WRITE(LOGUN,211) (IND   (NSTEP),NSTEP=NA1,NA2)
 211  FORMAT(' BR-F'   ,5X,12I10  )
      IF(NOF.EQ.0) WRITE(LOGUN,212) (RLOSTF(NSTEP),NSTEP=NA1,NA2)
 212  FORMAT(' SIGF'   ,6X,12E10.3)
      WRITE(LOGUN,230)( TOTAL(NSTEP),NSTEP=NA1,NA2)
 230  FORMAT(' TOTAL',5X,12E10.3)
      WRITE(LOGUN,231)(  AVGE(NSTEP),NSTEP=NA1,NA2)
 231  FORMAT(' EXCP',5X,12F10.1)
      WRITE(LOGUN, 232)( AVGJ(NSTEP),NSTEP=NA1,NA2)
 232  FORMAT(' SPINP',4X,12F10.1/)
      WRITE(LOGUN,233)( AVGEF(NSTEP),NSTEP=NA1,NA2)
 233  FORMAT(' EXCF',5X,12F10.1)
      WRITE(LOGUN, 234)(AVGJF(NSTEP),NSTEP=NA1,NA2)
 234  FORMAT(' SPINF',4X,12F10.1/)
      WRITE(LOGUN,235)( AVDJN(NSTEP),NSTEP=NA1,NA2)
 235  FORMAT(' DJN'  ,6X,12F10.2)
      WRITE(LOGUN,236)( AVDJP(NSTEP),NSTEP=NA1,NA2)
 236  FORMAT(' DJP'  ,6X,12F10.2)
      WRITE(LOGUN,237)( AVDJA(NSTEP),NSTEP=NA1,NA2)
 237  FORMAT(' DJA'  ,6X,12F10.2)
      WRITE(LOGUN,238)( EAVN (NSTEP),NSTEP=NA1,NA2)
 238  FORMAT(' AV.E N',3X,12F10.2)
      WRITE(LOGUN,239)( EAVP (NSTEP),NSTEP=NA1,NA2)
 239  FORMAT(' AV.E P',3X,12F10.2)
      WRITE(LOGUN,240)( EAVA (NSTEP),NSTEP=NA1,NA2)
 240  FORMAT(' AV.E A',3X,12F10.2)
      WRITE(LOGUN,251)(SUMEG (NSTEP),NSTEP=NA1,NA2)
 251  FORMAT(' SUM GAM',2X,12F10.1)
      WRITE(LOGUN,252)(SUMJG (NSTEP),NSTEP=NA1,NA2)
 252  FORMAT(' SPIN GAM',1X,12F10.1)
C
      WRITE(LOGUN,241) (TRIM(NSTEP),NSTEP=NA1,NA2)
 241  FORMAT(/ ' TRIM',6X,12E10.3)
      WRITE(LOGUN,245) (FLOST (NSTEP),NSTEP=NA1,NA2)
 245  FORMAT(' FLOST ',4X,12E10.3)
      WRITE(LOGUN,250) (RP(NSTEP),NSTEP=NA1,NA2)
 250  FORMAT(' RP',8X,12E10.3)
      WRITE(LOGUN,260) (RLOSTG(NSTEP),NSTEP=NA1,NA2)
 260  FORMAT(' RLOSTG',4X,12E10.3)
      WRITE(LOGUN,270) (RLOSTN(NSTEP),NSTEP=NA1,NA2)
 270  FORMAT(' RLOSTN',4X,12E10.3)
      WRITE(LOGUN,280) (RLOSTP(NSTEP),NSTEP=NA1,NA2)
 280  FORMAT(' RLOSTP',4X,12E10.3)
      WRITE(LOGUN,290) (RLOSTA(NSTEP),NSTEP=NA1,NA2)
 290  FORMAT(' RLOSTA',4X,12E10.3)
      WRITE(LOGUN,295) (IME   (NSTEP),NSTEP=NA1,NA2)
 295  FORMAT(' TIME', 5X,12I10//)
C-----------------------------------------------------------------
      IF(NA2.EQ.NA) GOTO 303
      NA1=NA1+12
      NA2=NA2+12
      NA2=MIN0(NA,NA2)
      GOTO 171
 303  IF(LPRINT.LT.3) GOTO 340
      ROUND=DEL(1)-AINT(DEL(1))
      WRITE(LOGUN,311) SYMB(1)
      CALL OUT1(SPECG,20,ROUND,1.D0,LOGUN)
      IF(NOE2.EQ.1) GOTO 304
      ROUND=DEL(1)-AINT(DEL(1))
      WRITE(LOGUN,310) SYMB(1)
      CALL OUT1(SPECQ,20,ROUND,1.D0,LOGUN)
 304  ROUND=DEL(2)-AINT(DEL(2))
      WRITE(LOGUN,310) SYMB(2)
      CALL OUT1(SPECN,25,ROUND,1.D0,LOGUN)
      ROUND=DEL(3)-AINT(DEL(3))
      WRITE(LOGUN,310) SYMB(3)
      CALL OUT1(SPECP,45,ROUND,1.D0,LOGUN)
      ROUND=DEL(4)-AINT(DEL(4))
      WRITE(LOGUN,310) SYMB(4)
      CALL OUT1(SPECA,80,ROUND,1.D0,LOGUN)
      IF(NOF.EQ.1) GOTO 340
      ROUND=DEL(5)-AINT(DEL(5))
      WRITE(LOGUN,310) SYMB(5)
      CALL OUT1(SPECF,20,ROUND,1.D0,LOGUN)
 310  FORMAT(' SPECTRUM ',A1)
 311  FORMAT(/' SPECTRUM ',A1)
 340  IF(LPRINT.GT.2) GOTO 999
      WRITE (LOGUN,350)
 350  FORMAT(/' STORAGE')
      WRITE(LOGUN,355)(STORE(NROW+1,NSTEP),NSTEP=1,NA)
      WRITE(LOGUN,355)(STORE(NROW+2,NSTEP),NSTEP=1,NA)
 355  FORMAT(15F4.0)
 600  FORMAT(6E12.4)
 999  IF(NOPUT.EQ.1) GOTO 9999
C-------------------------------------------------------------------
 1001 FORMAT(18I4)
 1002 FORMAT(3F8.2,4E12.4)
 1003 FORMAT(9F6.1)
 1004 FORMAT(6E12.4)
 9999 RETURN
      END