      SUBROUTINE SEQOUT(NROW,NSTEP,NOPUT)
C
C  Druckt Ausgabe innerhalb  einer Sequenz(N) - Schleife
C  letzte Modifikation 20.4.1990
C  Stand: 3.5.1994
C
      INCLUDE 'common.f'
C--------------------------------------------------------------------
C
      LOGUN=6
      MZ=KZ(NSTEP)
      MAA=MZ+IN(NSTEP)
      IF(LPRINT.LE.1)
     1WRITE(LOGUN,5 ) NROW,NSTEP,MAA,ELEMNT(MZ),ELAB,EXCIT
 5    FORMAT(' SEQOUT NROW,NSTEP',2I4,9X,'PARENT ',I3,A4,4X,'ELAB',F8.1,
     1 4X,'EXCIT',F8.1/)
      IF(NOPUT.EQ.1) GOTO 6
C
      IF(LPRINT.LT.3) THEN
         DO 31 K=1,KEG
         SPECGT(K)=SPECGT(K)+SPECG(K)
 31      SPECQT(K)=SPECQT(K)+SPECQ(K)
         DO 32 K=1,KEN
 32      SPECNT(K)=SPECNT(K)+ SPECN(K)
         DO 33 K=1,KEP1
 33      SPECPT(K)=SPECPT(K)+SPECP(K)
         DO 34 K=1,KEA1
 34      SPECAT(K)=SPECAT(K)+SPECA(K)
         DO 35 K=1,KEF
 35      SPECFT(K)=SPECFT(K)+SPECF(K)
      ENDIF
C
C                                     PUT P
C
      MN=M3*N3
      SUMP=0.
      DO 190 I=1,MN
 190  SUMP=SUMP+POPP(I)
      IF(LPRINT.LE.1)
     1WRITE(LOGUN,195) SUMP,SUMLOW
 195  FORMAT(' SUMP,SUMLOW',2E14.4)
      IF(  SUMP     .LT.SUMLOW) GOTO 200
       STORE(NROW+1,NSTEP)  = STORE(NROW+1,NSTEP)  +1.0001
      IUNIT=11-IU1
      IREAD=0
      I   =MZ-1
      II   =MAA-1
      CALL GETPUT(POPP,IPOPS,IUNIT,IREAD,M3,N3,EXMAX3,I,II,ACN,ZCN)
      IF(LPRINT.LE.1)
     1WRITE(LOGUN,196) IUNIT,II ,ELEMNT(I)
 196  FORMAT(' WROTE POPP ON UNIT',I4,15X,I3,A4)
C
C                                     PUT A
C
 200  MN=M4*N4
      SUMA=0.
      DO 204 I=1,MN
 204  SUMA=SUMA+POPA(I)
      IF(LPRINT.LE.1)
     1WRITE(LOGUN,208) SUMA,SUMLOW
 208  FORMAT(' SUMA,SUMLOW',2E14.4)
      IF(SUMA       .LT.SUMLOW) GOTO   6
       STORE(NROW+2,NSTEP+2)= STORE(NROW+2,NSTEP+2)+2.0001
      IUNIT=13-IU2
      IREAD=0
      IDUM=MAA-4
      I=MZ-2
      CALL GETPUT(POPA,IPOPS,IUNIT,IREAD,M4,N4,EXMAX4,I,IDUM,ACN,ZCN)
      IF(LPRINT.LE.1)
     1WRITE(LOGUN,212) IUNIT,IDUM,ELEMNT(I)
 212  FORMAT(' WROTE POPA ON UNIT',I4,15X,I3,A4)
C----------------------------------------------------------------------
C
 6    DO 216 J=1,N1
      YFISS(J)=YFISS(J)+YFISJ(J)
      DUM=1.
      IF(YPOPJ(J).GT.0.1E-20) DUM=YERJ(J)/YPOPJ(J)
      IF(PER(J).GT..1E-20) PER(J)=PER(J)*DUM
      DUMF=0.
      IF(YPOPJ(J).GT.0.1E-20) DUMF=YFISJ(J)/YPOPJ(J)
      PFIS(J)=PFIS(J)+(1.-PFIS(J))*DUMF
 216  CONTINUE
      IF(JFIS.EQ.0) GOTO 11
      IF(NROW.NE.1 .OR. NSTEP.NE.1) GOTO 226
      IACN=ACN+0.01
      IZCN=ZCN+0.01
      IF(JFIS.LT.4) WRITE(19,223) IACN,ELEMNT(IZCN),TOTAL(1),ELAB,N1
 223  FORMAT('C CNJ',I7,A4,E12.4,'(MB)',4X,
     1       'ELAB',F8.2,I6/'H: X-1   Y')
      IF(JFIS.LT.4) WRITE(19,231)(J,SPECJ(J),J=1,N1)
 226  IF(JFIS.EQ.1 .OR. JFIS.EQ.3) GOTO 228
      GOTO 11
 228  AMAA=MAA
      ZMZ=MZ
      AN=AMAA-ZMZ
      CALL FISROT(AMAA,ZMZ,AN,1.D0,DELR,DELSP,ERO,0.D0)
      CALL FISROT(AMAA,ZMZ,AN,0.D0,DELR,DELS0,ERO,0.D0 )
      DUMFF=DELSP-DELS0
      WRITE(19,230) MAA,ELEMNT(MZ),RLOSTF(NSTEP),N1,ELAB,DUMFF
 230  FORMAT('C FISSJ',I4,A4,E12.4,'(MB)',3X,'JMAX=',I4,3X,
     1       'ELAB',F8.2,4X,E12.4/'H: X-1   Y')
      WRITE(19,231)(J,YFISJ(J),J=1,N1)
 231  FORMAT(4(I4,E12.4,';'))
C--------------------------------------
C                             CALCULATE APROXIMATE TOTAL GAMMA ENERGY
 11   SUM=0.
      SUME=0.
      SUMJ=0.
      SUMEG(NSTEP)=0.
      SUMJG(NSTEP)=0.
      IF(NOG.EQ.1) GOTO 250
      DO 240 IEP=1,M1
      E=IEP-1
      EXCURR=EXMAX1-E
      JPEPMX=(N1-1)*M1+IEP
      RL=0.
      DO 236 JPEP=IEP,JPEPMX,M1
C     IF(PENTRY(JPEP).GT.0.) GOTO 234
      IF(TABLE(JPEP).EQ.SYMB(1) .OR. TABLE(JPEP).EQ.SYMB(6)) GOTO 234
      GOTO 235
 234  SUM=SUM+PENTRY(JPEP)
      SUME=SUME+PENTRY(JPEP)*EXCURR
      SUMJ=SUMJ+PENTRY(JPEP)*RL
 235  RL=RL+1.
 236  CONTINUE
 240  CONTINUE
      IF(SUM.GT.0.) SUMEG(NSTEP)=SUME/SUM
      IF(SUM.GT.0.) SUMJG(NSTEP)=SUMJ/SUM
C-----------------------------------------------
 250  IF(LPRINT.GT.1) GOTO 22
      WRITE(LOGUN,12) TOTAL(NSTEP)
 12   FORMAT(' TOTAL',E14.4)
      WRITE(LOGUN,14) FLOST(NSTEP),TRIM(NSTEP),RLOSTG(NSTEP),
     1 RLOSTN(NSTEP),
     2 RLOSTP(NSTEP),RLOSTA(NSTEP),RP(NSTEP)
 14   FORMAT(       ' FLOST(SUMPOP),TRIM(CUTOFF),RLOST(POPUL),RP '/
     1 7E13.4)
C----------------------------------------------------------------
      WRITE(LOGUN,20) MAA,ELEMNT(MZ)
 20   FORMAT(/' J SPECTRUM OF PARENT',I4,A4)
      ZERO=0.
      CALL OUT1(SPECJ,N1,ZERO,1.D0,6)
      WRITE(LOGUN,18) MAA,ELEMNT(MZ)
 18   FORMAT(/' J SPECTRUM OF FISS  ',I4,A4)
      ZERO=0.
      CALL OUT1(YFISJ,N1,ZERO,1.D0,6)
 19   ZERO=EXMAX1+1-MIN0(IEDIM,M1)
      WRITE(LOGUN,21) MAA,ELEMNT(MZ)
 21   FORMAT(/' E SPECTRUM OF PARENT',I4,A4)
      IDUM=MIN0(IEDIM,M1)
      CALL OUT1(SPECE,IDUM,ZERO,1.D0,6)
C----------------------------------------------  ENTRYJ,GSPEC  JFIS=2,3
 22   IF(JFIS.EQ.2 .OR. JFIS.EQ.3) GOTO 305
      GOTO 330
 305  CALL TOT(N1,M1,PENTRY,SPECJ,AMX,AVG,SIGGAM,SPECE,AVE,EXMAX1)
      WRITE(19,310) MAA,ELEMNT(MZ),AVG,AVE,SIGGAM,SIG(NSTEP)
 310  FORMAT('C ENTRYJ',I4,A4,1X,'AVJ=',F6.1,3X,'AVE=',F6.1,2X,
     1 'SIGENTRY',E10.3,2X,'SIGER',E10.3/'H: X-1   Y')
      WRITE(19,231)(J,SPECJ(J),J=1,N1)
      DO 320 IE=1,KEG
 320  SPECJ(IE)=SPECG(IE)+SPECQ(IE)
      WRITE(19,325)
 325  FORMAT('C GSPEC  1,2 ETC MEV'/'H: X   Y,H0')
      WRITE(19,231)(IE,SPECJ(IE),IE=1,16)
C----------------------------------------------  DJ-SPECS
 330  ILOG=6
      IF(LPRINT.GT.1) ILOG=0
      ZERO=1-LN
      IF(LPRINT.LT.2)WRITE(LOGUN,23)
 23   FORMAT(/' DJN SPEC')
      IDUM=2.*LN+1
      CALL OUT1(DJN,IDUM,ZERO,1.D0,ILOG)
      AVDJN(NSTEP)=ZERO
      ZERO=1-LP
      IF(LPRINT.LT.2)WRITE(LOGUN,25)
 25   FORMAT(/' DJP SPEC')
      IDUM=2.*LP+1
      CALL OUT1(DJP,IDUM,ZERO,1.D0,ILOG)
      AVDJP(NSTEP)=ZERO
      ZERO=1-LA
      IF(LPRINT.LT.2)WRITE(LOGUN,27)
 27   FORMAT(/' DJA SPEC')
      IDUM=2.*LA+1
      CALL OUT1(DJA,IDUM,ZERO,1.D0,ILOG)
      AVDJA(NSTEP)=ZERO
C--------------------------------------------
      IF(LPRINT.GT.2)GOTO 65
      IF(IOPT.EQ.0) GOTO 36
      WRITE(LOGUN,30) STRIPE
 30   FORMAT(/' J SPECTRUM(LINEAR) OF G RESIDUAL IN YRAST STRIPE',
     1        F6.1,' MEV'/)
      ZERO=0.
      CALL OUT1(FLAND,N1,ZERO,1.D0,6)
      CALL OUT2(FLAND,N1,1,0,0,0,0.D0,10,0,1)
 36   CONTINUE
C-------------------------------------------- INFO VARIOUS BRANCHES
      WRITE(LOGUN,60)
 60   FORMAT(/3X,'N   M   EXMAX  AV.EX. NW  MW  EXMAXW',6X,'Q',6X,
     1 'AL   DELTA',5X,'AVJ',6X,'DJ',8X,'TOTAL  BRANCH')
      DELTAJ=0.
      IRANCH=10000
      WRITE(LOGUN,100)N1,M1,EXMAX1,AVGE(NSTEP),NWG,MWG,EXMAXG,
     1 Q(1),AL(1),
     2   DELTA(1),AVGJ(NSTEP),DELTAJ,TOTAL(NSTEP),IRANCH,BLANK
C-N-----------------
 65   CALL TOT(N2,M2,POPN,SPECJ,AMX,AVG,SIGNN(NSTEP),SPECE,AVE,EXMAX2)
      IRANCH=SIGNN(NSTEP)*10000./TOTAL(NSTEP) +0.5
      DELTAJ=AVGJ(NSTEP)-AVG
      IF(LPRINT.LT.3)
     1WRITE(LOGUN,100)N2,M2,EXMAX2,AVE,NWN,MWN,EXMAXN,Q(2),AL(2),
     2DELTA(2),
     3            AVG        ,DELTAJ,SIGNN(NSTEP),IRANCH,SYMB(2)
C-P-----------------
      CALL TOT(N3,M3,POPP,SPECJ,AMX,AVG,SIGP (NSTEP),SPECE,AVE,EXMAX3)
      IRANCH=SIGP(NSTEP)*10000./TOTAL(NSTEP) +0.5
      DELTAJ=AVGJ(NSTEP)-AVG
      IF(LPRINT.LT.3)
     1WRITE(LOGUN,100)N3,M3,EXMAX3,AVE,NWP,MWP,EXMAXP,Q(3),AL(3),
     2            DELTA(3),
     3            AVG        ,DELTAJ,SIGP (NSTEP),IRANCH,SYMB(3)
C-A-----------------
      CALL TOT(N4,M4,POPA,SPECJ,AMX,AVG,SIGA (NSTEP),SPECE,AVE,EXMAX4)
      IF(LPRINT.GT.2) RETURN
      IRANCH=SIGA(NSTEP)*10000./TOTAL(NSTEP) +0.5
      DELTAJ=AVGJ(NSTEP)-AVG
      WRITE(LOGUN,100)N4,M4,EXMAX4,AVE,NWA,MWA,EXMAXA,Q(4),AL(4),
     2            DELTA(4),
     1            AVG        ,DELTAJ,SIGA (NSTEP),IRANCH,SYMB(4)
C-F-----------------
      IRANCH=SIGF(NSTEP)*10000./TOTAL(NSTEP) +0.5
      QF=-BFS(NSTEP,NROW)
      WRITE(LOGUN,101) AVGEF(NSTEP),NWF,MWF,EXMAXF,QF ,AL(5),DELTA(5),
     1           AVGJF(NSTEP),RLOSTF  (NSTEP),IRANCH,SYMB(5)
C-G-----------------
      IRANCH=SIG(NSTEP)*10000./TOTAL(NSTEP) +0.5
      WRITE(LOGUN,102) SIG(NSTEP),IRANCH,SYMB(1)
 102  FORMAT(80X,E14.3,I6,2X,A2)
 100  FORMAT(2I4,2F8.1,2I4,F8.1,5F8.2,E14.3,I6,2X,A2)
 101  FORMAT(16X, F8.1,2I4,F8.1,4F8.2,8X,E14.3,I6,2X,A2)
      WRITE(LOGUN,105) (AVESP(K),K=2,4),(SSP(K),K=2,4)
 105  FORMAT(/' SPECTRA N,P,A  AVE',3F8.2,8X,' SUMS',3E12.4)
C-------------------------------------------------------------
C PRINT-PLOTS (LPRINT=0)
      IF(LPRINT.GT.0) RETURN
      WRITE(LOGUN,120) NSTEP
 120  FORMAT(/' SPECTRA G(E1,E2),N,P,A,F   FACTOR 2.  NSTEP=',I3)
      WRITE(LOGUN,125) (SYMB(6),I=1,10)
 125  FORMAT(20(A1,4X))
      FACTOR=2.
      CALL OUT2(SPECG,KEG,1,1,0,0,FACTOR,10,0,0)
      WRITE(LOGUN,127) SYMB(1)
      IF(NOE2.EQ.0)CALL OUT2(SPECQ,KEG,1,1,0,0,2.D0,10,0,0)
      CALL OUT2(SPECN,KEN,1,0,0,0,FACTOR,10,0,0)
      WRITE(LOGUN,127) SYMB(2)
      CALL OUT2(SPECP,KEP1,1,0,0,0,FACTOR,10,0,0)
      WRITE(LOGUN,127) SYMB(3)
      CALL OUT2(SPECA,KEA1,1,0,0,0,FACTOR,10,0,0)
      WRITE(LOGUN,127) SYMB(4)
      IF(NOF.EQ.0)   CALL OUT2(SPECF,KEF,1,0,0,0,FACTOR ,10,0,0)
      IF(NOF.EQ.0)   WRITE(LOGUN,127) SYMB(5)
 127  FORMAT(1H+,55X,A2)
C
      IDUM=MAA-1
      WRITE(LOGUN,140) EXMAX2,NSTEP,IDUM,ELEMNT(MZ),MAA,ELEMNT(MZ)
 140  FORMAT(/6X,'POPN   FACTOR=2.',6X,'EXMAX=',F8.1,6X,'NSTEP=',I3,
     1       4X,'DAUGHTER',I4,A4,4X,'PARENT',I4,A4)
      M0=-EXMAX2
      CALL OUT2(POPN,M2,N2,M0,0,1,FACTOR,10,1,0)
C
      IF(N1.GT.M1) GOTO 162
      IF(M1.GT.127) GOTO 180
      WRITE(LOGUN,145) EXMAX1,NSTEP,MAA,ELEMNT(MZ)
 145  FORMAT(/6X,'EMISSION TABLE    EXCIT HOR',4X,'EXMAX=',F8.1,
     1        6X,'NSTEP=',I3,4X,'PARENT',I4,A4)
      WRITE(LOGUN,150) (SYMB(6),I=1,20)
 150  FORMAT(5X,20(A1,4X))
      IREP=0
      DO 160 J=1,N1
      JJ=    J*M1+1
      J0=J-1
      WRITE(LOGUN,170) J0,(TABLE(JJ-K),K=1,M1)
      DO 155 K=1,M1
      IF(TABLE(JJ-K).NE.BLANK) GOTO 160
 155  CONTINUE
      IREP=IREP+1
      IF(IREP.GE.2)GOTO 180
 160  CONTINUE
      GOTO 180
 162  JMAX=N1-1
      IF(N1.GT.127) GO TO 180
      WRITE(LOGUN,164) JMAX,NSTEP,MAA,ELEMNT(MZ)
 164  FORMAT(/6X,'EMISSION TABLE    SPINS HOR',4X,'JMAX=',I4,4X,
     1 'NSTEP=',I3,4X,'PARENT'  ,I4,A4)
      WRITE(LOGUN,125) (SYMB(6),I=1,20)
      IREP=0
      DO 168 K=1,M1
      K0=EXMAX1+2-K
      WRITE(LOGUN,170) K0,(TABLE(K+(J -1)*M1),J=1,N1)
      I=K-M1
      DO 165 J=1,N1
      I=I+M1
      IF(TABLE(I).NE.BLANK) GOTO 167
 165  CONTINUE
      IREP=IREP+1
      IF(IREP.GE.2)GOTO 180
      GOTO 168
 167  IREP=0
 168  CONTINUE
 170  FORMAT(I4,1X,127A1)
 180  CONTINUE
      RETURN
      END